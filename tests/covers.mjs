import assert from 'node:assert/strict';
import fs from 'node:fs';
import {execFileSync} from 'node:child_process';
const base='http://127.0.0.1:8787', checks=[];
async function api(p,method='GET',body,token,status=200,headers={}){
 const r=await fetch(base+'/api'+p,{method,headers:{'Content-Type':'application/json',...(token?{Authorization:'Bearer '+token}:{}),...headers},body:body===undefined?undefined:body instanceof Uint8Array?body:JSON.stringify(body)});
 assert.equal(r.status,status,p+': '+r.status);return r;
}
const guest=async()=>await(await api('/auth/guest','POST',{},null,201)).json();
const owner=await guest(),other=await guest();
const payload={title:'Cover integration fixture',story:'Synthetic only, never a live meal.',organizer:'Test',scene:'other',meals:[{name:'Synthetic meal',quantity:1,specification:'Do not order'}],location:{name:'Test',address:'Public test place',lat:31,lng:121},mealAt:Date.now()+3600000,acceptBy:Date.now()+1800000,referenceCents:null,referenceAt:null,recurringDays:null,privateDelivery:{contactName:'Test',phone:'LOCAL-PRIVATE',detail:''},consent:true,deliveryCheckedAt:Date.now()};
const n=await(await api('/needs','POST',payload,owner.token,201)).json();
const bytes=fs.readFileSync('public/images/covers/other.webp');
const headers={'Content-Type':'image/webp','X-Public-Image-Consent':'true'};
await api(`/needs/${n.id}/cover`,'PUT',bytes,null,401,headers);
await api(`/needs/${n.id}/cover`,'PUT',bytes,other.token,403,headers);
checks.push('Only the requester may upload a cover');
await api(`/needs/${n.id}/cover`,'PUT',bytes,owner.token,400,{'Content-Type':'image/webp'});
await api(`/needs/${n.id}/cover`,'PUT',Buffer.from('<svg onload="alert(1)"/>'),owner.token,400,headers);
await api(`/needs/${n.id}/cover`,'PUT',new Uint8Array(400001),owner.token,413,headers);
checks.push('Consent, static WebP format and byte limit enforced');
await api(`/needs/${n.id}/cover`,'PUT',bytes,owner.token,200,headers);
await api(`/needs/${n.id}/cover`,'GET',undefined,null,404);
await api(`/private/needs/${n.id}/cover`,'GET',undefined,other.token,403);
const own=await api(`/private/needs/${n.id}/cover`,'GET',undefined,owner.token);
assert.deepEqual(Buffer.from(await own.arrayBuffer()),bytes);
checks.push('Draft cover is private and survives authenticated retrieval');
await api(`/needs/${n.id}/publish`,'POST',{version:1,confirmed:true},owner.token);
const pub=await(await api(`/needs/${n.id}`)).json();assert(pub.coverUrl);
const image=await api(`/needs/${n.id}/cover`);assert.equal(image.headers.get('content-type'),'image/webp');assert.equal(image.headers.get('x-content-type-options'),'nosniff');
assert.deepEqual(Buffer.from(await image.arrayBuffer()),bytes);
checks.push('Published cover is publicly retrievable as a nosniff WebP');
const rev=pub.coverRevision;
await api(`/needs/${n.id}/cover`,'PUT',fs.readFileSync('public/images/covers/birthday.webp'),owner.token,200,headers);
assert.notEqual((await(await api(`/needs/${n.id}`)).json()).coverRevision,rev);
checks.push('Replacing the cover changes its revision without changing the meal version');
const sql=s=>execFileSync('node_modules/.bin/wrangler',['d1','execute','mc4need-db','--local','--command',s],{stdio:'pipe'});
sql(`UPDATE needs SET hidden=1 WHERE id='${n.id}'`);
await api(`/needs/${n.id}/cover`,'GET',undefined,null,404);
checks.push('Hiding a need also hides its public cover');
await api(`/needs/${n.id}/cover`,'DELETE',undefined,other.token,403);
await api(`/needs/${n.id}/cover`,'DELETE',undefined,owner.token);
await api(`/private/needs/${n.id}/cover`,'GET',undefined,owner.token,404);
assert.equal((await(await api(`/private/needs/${n.id}`,'GET',undefined,owner.token)).json()).coverUrl,null);
checks.push('Removing a cover deletes its data and restores the default selection');
fs.writeFileSync('reports/cover-results.json',JSON.stringify({date:new Date().toISOString(),environment:'Local Worker and synthetic need only',passed:checks.length,checks},null,2)+'\n');
console.log(checks);
